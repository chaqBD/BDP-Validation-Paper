"""Regenerates the capped-vs-full sampling-sensitivity table for the two
row-comparison-dependent defects (exact duplicate, group/customer overlap), one
representative model family (LightGBM), both datasets.

Capped and uncapped checks are run against the SAME fitted pipeline and the SAME
prediction vector in a single pass (fit once, score once, then run the gate twice
-- once on the full index arrays, once on a capped subsample built the identical
way `src.gate_integration.run_gate_report` caps its own input). An earlier version
of this script instead read the capped row back from `release_review_battery.csv`,
which silently went stale the moment that file was regenerated by a later,
corrected run of the main battery -- the uncapped and capped rows could then come
from two different population/splitter versions without anything in the code
flagging it. This version cannot go stale that way: there is only one run, one
fit, one set of predictions, and both rows are derived from it.

Every gate report this script produces is written to its own uniquely named path
under `gate_json/sampling_sensitivity/`, never reusing a tag the main battery or
any other script writes to, and the exact path is recorded in the output CSV
(`gate_json_path`) so every row is traceable to the report it was read from.

Also distinguishes genuinely injected row duplication from coincidental
feature-vector collisions: `case_exact_duplicate` injects duplicate rows by exact
source-row index (ground truth, known exactly), while the gate's
overlap-with-training check matches on hashed feature vectors, which can also
count rows that merely happen to collide on a narrower or lower-cardinality
feature set without being an injected duplicate at all.
"""
import sys
import warnings
from pathlib import Path

warnings.filterwarnings("ignore")
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import numpy as np
import pandas as pd

from src.config import RESULTS_DIR
from src.gate_integration import GATE_CONFIG, MAX_GATE_ROWS, _cap
from src.release_cases import (_reference, case_exact_duplicate, case_group_overlap_dataco,
                                case_group_overlap_olist)
from src.release_review import fit_predict
from bdp_model_gate import StructuredGateContext, ModelGate
from bdp_model_gate.structured import default_structured_checks

OUT_DIR = RESULTS_DIR / "release_review"
JSON_DIR = OUT_DIR / "gate_json" / "sampling_sensitivity"
JSON_DIR.mkdir(parents=True, exist_ok=True)


def extract_split_overlap(report):
    out = {}
    for r in report.results:
        if r.check_name == "split_overlap":
            out[r.metadata.get("check", "unknown")] = {
                "flag": r.flag, "detail": r.detail, "metadata": r.metadata}
    return out


def extract_split_overlap_json_path(path):
    """Same extraction as `extract_split_overlap`, but from a saved gate-report
    JSON file on disk (as `run_one_case` / `run_gate_report` writes it) rather
    than a live report object -- used by `run_heldout_evaluation.py` to pull the
    duplication-specific check's own flag and fraction for every severity/seed
    instance, each written to its own uniquely tagged path.
    """
    import json
    if not Path(path).exists():
        return {}
    with open(path, encoding="utf-8") as f:
        gjson = json.load(f)
    out = {}
    for cat, items in gjson.get("results_by_category", {}).items():
        if cat != "validation":
            continue
        for it in items:
            if it.get("check_name") == "split_overlap":
                meta = it.get("metadata", {})
                out[meta.get("check", "unknown")] = {"flag": it.get("flag"), "metadata": meta}
    return out


def _run_gate(pipe, X_train, X_test, y_test, p_test, dataset, tag):
    model_card = {"training_data_source": dataset, "validation_strategy": "out_of_time",
                  "use_case": "supply_chain_late_delivery_prediction",
                  "legal_basis": "legitimate interest - internal supply-chain operations research",
                  "data_minimization_justification": "order/customer identifiers excluded"}
    ctx = StructuredGateContext(model=pipe, X=X_test, y_true=y_test, y_pred=p_test,
                                X_train=X_train, model_card=model_card)
    gate = ModelGate(checks=default_structured_checks(GATE_CONFIG))
    report = gate.run(ctx)
    json_path = JSON_DIR / f"{tag}.json"
    try:
        report.to_json(str(json_path))
    except Exception:
        import json as _json
        with open(json_path, "w", encoding="utf-8") as f:
            _json.dump({"gate_status": report.gate_status, "tag": tag}, f)
    overlap = extract_split_overlap(report)
    return {
        "n_train": len(X_train), "n_test": len(X_test),
        "gate_status": report.gate_status, "model_score": report.model_score,
        "duplicates_within_validation_flag": overlap.get("duplicates_within_validation", {}).get("flag"),
        "duplicates_within_validation_fraction":
            overlap.get("duplicates_within_validation", {}).get("metadata", {}).get("duplicate_fraction"),
        "overlap_with_training_flag": overlap.get("overlap_with_training", {}).get("flag"),
        "overlap_with_training_fraction":
            overlap.get("overlap_with_training", {}).get("metadata", {}).get("overlap_fraction"),
        "overlap_with_training_n":
            overlap.get("overlap_with_training", {}).get("metadata", {}).get("n_overlapping"),
        "gate_json_path": str(json_path),
    }


def run_capped_and_uncapped(dataset, case_name, case, family="gbm"):
    """Fits one pipeline on the case's full training set, scores the case's full
    test set once, then runs the gate twice against that single fit: once on the
    full index arrays, once on a capped subsample built the same way
    `run_gate_report` caps its own input (`_cap`, seed=0). Both rows below
    therefore differ only in how much of the identical fit/prediction the gate
    was shown, never in which model was fitted or which rows were scored.
    """
    ref = _reference(dataset)
    X, y = ref["X"], ref["y"]
    train_idx, test_idx = case["train_idx"], case["test_idx"]
    X_train, y_train = X.iloc[train_idx], y.iloc[train_idx]
    X_test, y_test = X.iloc[test_idx], y.iloc[test_idx]
    pipe, p_test = fit_predict(family, X_train, y_train, X_test, ref["num"], ref["cat"])

    full = _run_gate(pipe, X_train, X_test, y_test.values, p_test, dataset,
                      f"{dataset}_{case_name}_{family}_full")
    full.update({"dataset": dataset, "case": case_name, "sample": "full"})

    X_train_capped = _cap(X_train, MAX_GATE_ROWS)
    if len(X_test) > MAX_GATE_ROWS:
        rng = np.random.default_rng(0)
        test_pos = np.sort(rng.choice(len(X_test), size=MAX_GATE_ROWS, replace=False))
        X_test_capped = X_test.iloc[test_pos]
        y_test_capped = y_test.values[test_pos]
        p_test_capped = p_test[test_pos]
    else:
        X_test_capped, y_test_capped, p_test_capped = X_test, y_test.values, p_test
    capped = _run_gate(pipe, X_train_capped, X_test_capped, y_test_capped, p_test_capped,
                        dataset, f"{dataset}_{case_name}_{family}_capped_{MAX_GATE_ROWS}")
    capped.update({"dataset": dataset, "case": case_name, "sample": f"capped_{MAX_GATE_ROWS}"})
    return full, capped


def coincidental_match_count(dataset, case):
    """Distinguishes test rows the gate's hash-based overlap-with-training check
    would flag because they were genuinely injected (their exact row position is
    recorded by `case_exact_duplicate` as `injected_test_rows`, the ground truth)
    from test rows whose feature vector merely happens to coincide with some
    training row's hash without having been injected at all.
    """
    ref = _reference(dataset)
    X = ref["X"]
    train_idx, test_idx = case["train_idx"], case["test_idx"]
    injected_test_rows = set(case.get("injected_test_rows", np.array([], dtype=int)).tolist())

    train_hashes = pd.util.hash_pandas_object(X.iloc[train_idx], index=False).values
    test_hashes = pd.util.hash_pandas_object(X.iloc[test_idx], index=False).values
    train_hash_set = set(train_hashes.tolist())
    matched_mask = np.isin(test_hashes, list(train_hash_set))
    matched_test_rows = set(test_idx[matched_mask].tolist())

    n_injected_recovered = len(injected_test_rows & matched_test_rows)
    n_coincidental = len(matched_test_rows - injected_test_rows)
    n_injected_missed = len(injected_test_rows - matched_test_rows)
    return {
        "n_injected": len(injected_test_rows),
        "n_hash_matches": len(matched_test_rows),
        "n_injected_recovered": n_injected_recovered,
        "n_coincidental": n_coincidental,
        "n_injected_missed": n_injected_missed,
    }


if __name__ == "__main__":
    rows = []
    for dataset, case_name, case_builder in [
        ("dataco", "defect_exact_duplicate", lambda: case_exact_duplicate(_reference("dataco"))),
        ("olist", "defect_exact_duplicate", lambda: case_exact_duplicate(_reference("olist"))),
        ("dataco", "defect_group_overlap", lambda: case_group_overlap_dataco(_reference("dataco"))),
        ("olist", "defect_group_overlap", lambda: case_group_overlap_olist(_reference("olist"))),
    ]:
        case = case_builder()
        full, capped = run_capped_and_uncapped(dataset, case_name, case)
        rows.append(full)
        rows.append(capped)
        print(f"{dataset} {case_name} FULL:   {full['overlap_with_training_flag']} "
              f"{full['overlap_with_training_fraction']} {full['gate_status']}")
        print(f"{dataset} {case_name} CAPPED: {capped['overlap_with_training_flag']} "
              f"{capped['overlap_with_training_fraction']} {capped['gate_status']}")

        if case_name == "defect_exact_duplicate":
            cm = coincidental_match_count(dataset, case)
            print(dataset, case_name, "coincidental-match check:", cm)

    out = pd.DataFrame(rows)
    out.to_csv(OUT_DIR / "sampling_sensitivity.csv", index=False)
    print("\nSaved to", OUT_DIR / "sampling_sensitivity.csv")

    # Dataset-specific capped/full understatement ratio, computed directly from
    # this run's own numbers rather than stated generically for both datasets.
    print("\n" + "=" * 100)
    print("Capped-vs-full understatement ratio (overlap_with_training_fraction), exact-duplicate defect")
    print("=" * 100)
    for dataset in ["dataco", "olist"]:
        d = out[(out.case == "defect_exact_duplicate") & (out.dataset == dataset)]
        full_frac = d[d["sample"] == "full"]["overlap_with_training_fraction"].iloc[0]
        capped_frac = d[d["sample"] == f"capped_{MAX_GATE_ROWS}"]["overlap_with_training_fraction"].iloc[0]
        if capped_frac and capped_frac > 0:
            print(f"  {dataset}: full={full_frac:.4f} capped={capped_frac:.4f} "
                  f"ratio={full_frac/capped_frac:.1f}x understated")
        else:
            print(f"  {dataset}: full={full_frac:.4f} capped={capped_frac} (capped fraction is zero/undefined)")
    print(out.to_string())
